"""Генератор синтетического датасета для тестов.

Реальные цеховые файлы в репозиторий не выкладываются, поэтому тесты
работают на синтетике. Датасет описан явно в SHIFT и EDGE_CASES: эталонные
суммы считаются из этого описания, а не из разбора сгенерированных файлов,
поэтому тест проверяет парсер независимым путём.

Воспроизводит структурные особенности формата NCeXpress FMS, на которых
ломается наивный разбор:

  * одна деталь может лежать в нескольких блоках PART_DATA одного файла;
  * SHEET_COUNT встречается в файле дважды, второй раз — в строке
    IF (SHEET_COUNT > R400) ... , которую нельзя принимать за объявление;
  * блоки с PART_NAME="SCRAP" — обрезки, в учёт не идут;
  * .nc пишется с LF, .fms — с CRLF;
  * файлы бывают в разных однобайтовых кодировках.

Запуск:  python3 tools/make_fixtures.py
"""

